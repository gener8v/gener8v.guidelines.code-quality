import unittest

from cq_measure.fixture_repository import fixture_repo
from cq_measure.source import roles
from cq_measure.source.source_file import SourceFile


class RolesTest(unittest.TestCase):
    def test_test_subjects(self):
        self.assertEqual(roles.test_subject("a/test_invoice.py"), "invoice")
        self.assertEqual(roles.test_subject("a/invoice_test.py"), "invoice")
        self.assertEqual(roles.test_subject("a/invoice.integration.test.ts"), "invoice")
        self.assertEqual(roles.test_subject("a/InvoiceTest.java"), "Invoice")
        self.assertIsNone(roles.test_subject("a/invoice.py"))

    def test_test_trees_and_support(self):
        self.assertTrue(roles.in_test_tree("tests/billing/factories.py"))
        self.assertTrue(roles.is_testish("src/conftest.py"))
        self.assertFalse(roles.is_testish("src/billing/invoice.py"))

    def test_generated_marker_and_dirs(self):
        self.assertEqual(roles.generated_marker_line(["// Code generated by tool. DO NOT EDIT.", "package x"]), 1)
        self.assertIsNone(roles.generated_marker_line(['MARKER = "DO NOT EDIT"']))
        self.assertTrue(roles.in_generated_dir("src/__generated__/x.ts"))

    def test_entry_points_and_cli(self):
        files = {"tool.py": 'if __name__ == "__main__":\n    run()\n', "lib.py": "x = 1\n", "scripts/a.py": ""}
        with fixture_repo(files) as root:
            self.assertTrue(roles.is_cli_entry(SourceFile(root, "tool.py")))
            self.assertTrue(roles.is_cli_entry(SourceFile(root, "scripts/a.py")))
            self.assertFalse(roles.is_entry_point(SourceFile(root, "lib.py"), ["**/main.*"]))
        self.assertTrue(roles.in_script_dir("bin/x.py"))
        self.assertTrue(roles.is_config_name("vite.config.ts"))
        self.assertTrue(roles.is_framework_file("app/users/page.tsx"))
        self.assertTrue(roles.in_route_tree("app/users/page.tsx"))
        self.assertFalse(roles.in_route_tree("app/users/view.py"))


if __name__ == "__main__":
    unittest.main()
