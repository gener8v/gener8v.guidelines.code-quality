import unittest

from cq_measure.fixture_repository import findings_for


class PackageByLayerTest(unittest.TestCase):
    def test_layers(self):
        files = {"src/controllers/a.ts": "", "src/services/a.ts": "", "src/models/a.ts": ""}
        self.assertEqual([f.path for f in findings_for(files, "package-by-layer")], ["src"])
        self.assertEqual(findings_for({"src/billing/a.ts": "", "src/services/a.ts": ""}, "package-by-layer"), [])


class SingleChildDirTest(unittest.TestCase):
    def test_lone_child(self):
        self.assertEqual([f.path for f in findings_for({"docs/adr/a.md": ""}, "single-child-dir")], ["docs"])

    def test_exemptions(self):
        files = {"src/pkg/a.py": "", "src/main/java/com/A.java": "", "cmd/server/main.go": "", "app/settings/profile/page.tsx": ""}
        self.assertEqual(findings_for(files, "single-child-dir"), [])


class GeneratedPlacementTest(unittest.TestCase):
    def test_marker_outside_generated_dir(self):
        marker = "// Code generated by protoc. DO NOT EDIT.\npackage api\n"
        found = findings_for({"api/types.go": marker, "api/generated/more.go": marker}, "generated-placement")
        self.assertEqual([(f.path, f.line) for f in found], [("api/types.go", 1)])
        self.assertEqual(findings_for({"api/types.go": "package api\n"}, "generated-placement"), [])


class ScriptPlacementTest(unittest.TestCase):
    def test_shell_script_in_source_dir(self):
        files = {"src/billing/run.sh": "", "src/billing/a.py": "", "scripts/deploy.sh": "", "install.sh": "", "docker/entry.sh": ""}
        self.assertEqual([f.path for f in findings_for(files, "script-placement")], ["src/billing/run.sh"])


if __name__ == "__main__":
    unittest.main()
